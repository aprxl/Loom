//! The Unicode tables of the Lua runtime (`runtime/rt/core.lua`) are made
//! from Rust's own, so both backends agree on every character: this test
//! writes them, between the markers in core.lua, and fails when they are
//! stale. `LOOM_BLESS=1 cargo test -p loom_vm --test unicode_tables` updates
//! them (after a Rust upgrade).

use std::fmt::Write as _;
use std::path::Path;

const BEGIN: &str = "-- BEGIN unicode tables (generated by crates/loom_vm/tests/unicode_tables.rs)";
const END: &str = "-- END unicode tables";

/// `lo-hi` pairs in hex for the characters `keep` says yes to.
fn ranges(keep: impl Fn(char) -> bool) -> String {
    let mut out = String::new();
    let mut start: Option<u32> = None;
    let mut last = 0;
    let flush = |out: &mut String, start: u32, end: u32| {
        if !out.is_empty() {
            out.push(',');
        }
        if start == end {
            write!(out, "{start:x}").expect("writes to a string");
        } else {
            write!(out, "{start:x}-{end:x}").expect("writes to a string");
        }
    };
    for cp in 0..=0x10FFFFu32 {
        let yes = char::from_u32(cp).is_some_and(&keep);
        match (yes, start) {
            (true, None) => start = Some(cp),
            (false, Some(s)) => {
                flush(&mut out, s, last);
                start = None;
            }
            _ => {}
        }
        last = cp;
    }
    if let Some(s) = start {
        flush(&mut out, s, last);
    }
    out
}

/// `cp:c1.c2` for every character whose mapping isn't itself.
fn mapping<I: Iterator<Item = char>>(map: impl Fn(char) -> I) -> String {
    let mut entries = Vec::new();
    for cp in 0x80..=0x10FFFFu32 {
        let Some(c) = char::from_u32(cp) else { continue };
        let to: Vec<char> = map(c).collect();
        if to != [c] {
            let parts: Vec<String> = to.iter().map(|t| format!("{:x}", *t as u32)).collect();
            entries.push(format!("{cp:x}:{}", parts.join(".")));
        }
    }
    entries.join(",")
}

fn block() -> String {
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("local UNICODE = {\n");
    for (name, data) in [
        ("alphabetic", ranges(char::is_alphabetic)),
        ("numeric", ranges(char::is_numeric)),
        ("upper", ranges(char::is_uppercase)),
        ("lower", ranges(char::is_lowercase)),
        ("to_upper", mapping(|c| c.to_uppercase())),
        ("to_lower", mapping(|c| c.to_lowercase())),
    ] {
        writeln!(out, "  {name} = \"{data}\",").expect("writes to a string");
    }
    out.push_str("}\n");
    out.push_str(END);
    out
}

#[test]
fn the_lua_tables_are_current() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runtime/rt/core.lua");
    let text = std::fs::read_to_string(&path).expect("core.lua");
    let crlf = text.contains("\r\n");
    let text = text.replace("\r\n", "\n");
    let (start, end) = (text.find(BEGIN).expect("begin marker"), text.find(END).expect("end marker") + END.len());
    let fresh = block();
    if text[start..end] == fresh {
        return;
    }
    if std::env::var_os("LOOM_BLESS").is_none() {
        panic!("the Unicode tables in core.lua are stale (LOOM_BLESS=1 updates them)");
    }
    let mut updated = format!("{}{fresh}{}", &text[..start], &text[end..]);
    if crlf {
        updated = updated.replace('\n', "\r\n");
    }
    std::fs::write(&path, updated).expect("core.lua is writable");
}
