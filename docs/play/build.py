# Builds the docs' playground: `loom-play` (crates/loom_play) for WebAssembly,
# packed into docs/play/loom-wasm.js, the file the pages load when a sample is
# first run.
#
#   python docs/play/build.py           build, pack, then (with Node) run every
#                                       sample of the docs through the wasm
#   python docs/play/build.py --check   only run the samples through the wasm
#                                       loom-wasm.js holds
#
# Rebuild it when the compiler or the VM changes what a program does: the
# pages' Run buttons use this build, not your `loom`. `python docs/gen.py
# --check` says when the sources have changed since (the `sources` hash).
#
# Why a .js file and not a .wasm: `loom docs` opens the pages from file://,
# where a browser fetches nothing, but a <script src> still loads. The module
# is gzipped (the browser's DecompressionStream undoes it) and base64-encoded.
#
# Needs the wasm32-wasip1 target: `rustup target add wasm32-wasip1`.
import base64
import gzip
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "loom-wasm.js")
WASM = os.path.join(ROOT, "target", "wasm32-wasip1", "release", "loom-play.wasm")
SAMPLES = os.path.join(ROOT, "docs", "lang", "samples")

# What the wasm is built from: these crates' sources and manifests, the
# standard library (embedded in the compiler) and the lock file.
CRATES = ["loom_syntax", "loom_isa", "loom_sys", "loom_vm", "loom_compiler", "loom_runner", "loom_play"]


def source_files():
    files = [os.path.join(ROOT, "Cargo.lock"), os.path.join(ROOT, "Cargo.toml")]
    for crate in CRATES:
        base = os.path.join(ROOT, "crates", crate)
        files.append(os.path.join(base, "Cargo.toml"))
        if os.path.exists(os.path.join(base, "build.rs")):
            files.append(os.path.join(base, "build.rs"))
        for dirpath, _, names in os.walk(os.path.join(base, "src")):
            files += [os.path.join(dirpath, n) for n in names]
    for dirpath, _, names in os.walk(os.path.join(ROOT, "runtime")):
        files += [os.path.join(dirpath, n) for n in names if n.endswith((".loom", ".lua"))]
    return sorted(files)


def sources_hash():
    """A hash of what the wasm is built from, line endings normalized."""
    h = hashlib.sha256()
    for path in source_files():
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        with open(path, "rb") as f:
            data = f.read().replace(b"\r\n", b"\n")
        h.update(rel.encode() + b"\0" + data + b"\0")
    return h.hexdigest()[:16]


def built_hash():
    """The `sources` hash loom-wasm.js was built from, or None."""
    if not os.path.exists(OUT):
        return None
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            if line.startswith("// sources: "):
                return line.split()[2]
    return None


def build():
    env = dict(os.environ)
    # The workspace's rustflags (.cargo/config.toml) tune the native dispatch
    # loop's layout; for wasm they only make the module bigger.
    env["CARGO_ENCODED_RUSTFLAGS"] = ""
    cmd = ["cargo", "build", "-p", "loom_play", "--bin", "loom-play", "--target", "wasm32-wasip1", "--release",
           "--config", 'profile.release.opt-level="s"', "--config", 'profile.release.strip="symbols"']
    print("$", " ".join(cmd))
    subprocess.run(cmd, cwd=ROOT, env=env, check=True)


def pack():
    with open(WASM, "rb") as f:
        wasm = f.read()
    packed = base64.b64encode(gzip.compress(wasm, 9, mtime=0)).decode("ascii")
    text = (
        "// Generated by docs/play/build.py: the Loom compiler and Treadle, built for\n"
        "// WebAssembly (wasm32-wasip1), gzipped and base64-encoded. Don't edit.\n"
        f"// sources: {sources_hash()}\n"
        f"// wasm: {len(wasm)} bytes\n"
        f"window.LOOM_WASM = {json.dumps(packed)};\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(wasm)} bytes of wasm, {len(text)} of script")


def unpack(dest):
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            if line.startswith("window.LOOM_WASM = "):
                packed = json.loads(line[len("window.LOOM_WASM = "):].rstrip().rstrip(";"))
                break
        else:
            raise SystemExit(f"{OUT}: no window.LOOM_WASM line")
    with open(dest, "wb") as f:
        f.write(gzip.decompress(base64.b64decode(packed)))


def skipped():
    with open(os.path.join(HERE, "skip.txt"), encoding="utf-8") as f:
        return {ln.split()[0] for ln in f if ln.strip() and not ln.startswith("#")}


def check_samples():
    """Runs every sample through the wasm in loom-wasm.js with Node's WASI and
    compares with its .out, as crates/loom_play/tests/samples.rs does natively."""
    node = shutil.which("node")
    if not node:
        print("no node on PATH: skipped running the samples through the wasm")
        return True
    sys.path.insert(0, os.path.join(ROOT, "docs"))
    import samples  # noqa: E402

    skip = skipped()
    names = [n for n in samples.sample_names() if n not in skip]
    with tempfile.TemporaryDirectory() as tmp:
        wasm = os.path.join(tmp, "loom-play.wasm")
        unpack(wasm)
        jobs, results = [], []
        for name in names:
            mode, _ = samples.directive(name)
            play_mode = {"run": "run", "unravel": "run", "error": "run", "check": "check",
                         "check-fail": "check", "test": "test", "test-fail": "test"}[mode]
            jobs.append({"name": name})
            with open(os.path.join(SAMPLES, name + ".loom"), "rb") as src:
                t = time.perf_counter()
                p = subprocess.run([node, "--no-warnings", os.path.join(HERE, "check.mjs"), wasm,
                                    f"docs/lang/samples/{name}.loom", play_mode],
                                   stdin=src, capture_output=True, timeout=120)
            results.append({"code": p.returncode, "ms": round((time.perf_counter() - t) * 1000),
                            "stdout": p.stdout.decode("utf-8", "replace"),
                            "stderr": p.stderr.decode("utf-8", "replace")})
    problems = []
    for job, res in zip(jobs, results):
        name = job["name"]
        mode, _ = samples.directive(name)
        _, want_code, has_out = samples.MODES[mode]
        out = res["stdout"].replace("\r\n", "\n")
        err = res["stderr"].replace("\r\n", "\n")
        got = samples.combine(out, err) if has_out else ""
        want = (samples.read_out(name) or "") if has_out else ""
        if res["code"] != want_code or got != want:
            problems.append(f"{name}: exit {res['code']} (want {want_code})\n--- want\n{want}--- got\n{got}")
    for p in problems:
        print(" -", p)
    print(f"{len(names)} samples through the wasm with {node}, {len(problems)} differ")
    return not problems


def main(argv):
    if "--check" not in argv:
        build()
        pack()
    ok = check_samples()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
